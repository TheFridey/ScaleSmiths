const adminOrigin=process.env.EXPANSION_ADMIN_BASE_URL
const webOrigin=process.env.EXPANSION_WEB_BASE_URL
test.skip(!adminOrigin || !webOrigin,'Explicit isolated Expansion web/admin servers are required.')
const password='Expansion-Demo-Only-2026'
function localOrigin(value:string|undefined) {
  const url=new URL(value || 'invalid:')
  if(!['localhost','127.0.0.1'].includes(url.hostname) || !['3102','3103'].includes(url.port)) throw new Error('Refusing Expansion browser mutations outside explicit local demo servers.')
  return url.origin
}
async function login(page:Page,email:string) {
  await page.goto(`${localOrigin(adminOrigin)}/login`)
  await page.getByLabel('Email',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  if(email==='expansion-founder@example.invalid') await page.getByLabel(/^Authenticator code/).fill(generateTotp('JBSWY3DPEHPK3PXP'))
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.waitForURL(/\/(partner|command-centre)$/)
}
async function snapshot(context:BrowserContext,founder=false) {
  const response=await context.request.get(`${localOrigin(adminOrigin)}/api/${founder?'expansion':'partner'}`)
  expect(response.ok(),await response.text()).toBeTruthy()
  return response.json()
}
async function command(context:BrowserContext,input:Record<string,unknown>,founder=false) {
  const response=await context.request.post(`${localOrigin(adminOrigin)}/api/${founder?'expansion':'partner'}`,{headers:{origin:localOrigin(adminOrigin)},data:input,timeout:180000})
  expect(response.ok(),await response.text()).toBeTruthy()
  return (await response.json()).result
}

