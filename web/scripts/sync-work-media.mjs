#!/usr/bin/env node
// Regenerates src/lib/work-media-manifest.ts from the real screenshots in public/images/work.
// Run after adding or removing case-study imagery: `npm run work-media:sync`.
// work-media.test.ts fails when the manifest and the files on disk disagree.
import { readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative, sep } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const appDir = join(dirname(fileURLToPath(import.meta.url)), "..")
const publicDir = join(appDir, "public")
const workDir = join(publicDir, "images", "work")
const manifestPath = join(appDir, "src", "lib", "work-media-manifest.ts")
const IMAGE_EXTENSIONS = /\.(?:webp|avif|png|jpe?g)$/i

export function listWorkMedia(root = workDir) {
  const files = []
  const walk = (dir) => {
    let entries
    try {
      entries = readdirSync(dir)
    } catch {
      return
    }
    for (const entry of entries) {
      const path = join(dir, entry)
      if (statSync(path).isDirectory()) walk(path)
      else if (IMAGE_EXTENSIONS.test(entry)) files.push(`/${relative(publicDir, path).split(sep).join("/")}`)
    }
  }
  walk(root)
  return files.sort()
}

export function renderManifest(files) {
  return [
    "// Generated by scripts/sync-work-media.mjs. Do not edit by hand; run `npm run work-media:sync`.",
    "export const availableWorkMedia: readonly string[] = [",
    ...files.map((file) => `  ${JSON.stringify(file)},`),
    "]",
    "",
  ].join("\n")
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = listWorkMedia()
  writeFileSync(manifestPath, renderManifest(files))
  console.log(`work media manifest: ${files.length} image(s)`)
}
